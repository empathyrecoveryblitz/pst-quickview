fn write_app_permissions(out_dir: &Path) -> PathBuf {
    let permissions_path = out_dir.join("pst-quickview-app-permissions.toml");
    let mut permissions = String::from(
        "# Generated by build.rs in Cargo's build-output directory.\n\
         # Application commands are denied unless a window capability references an allow permission.\n",
    );

    for command in APP_COMMANDS {
        let identifier = command.replace('_', "-");
        writeln!(
            permissions,
            "\n[[permission]]\nidentifier = \"allow-{identifier}\"\n\
             description = \"Allows the {command} application command.\"\n\
             commands.allow = [\"{command}\"]"
        )
        .expect("writing app permissions to a string cannot fail");
    }

    fs::write(&permissions_path, permissions)
        .expect("failed to write generated application-command permissions");
    permissions_path
}

fn main() {
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("Cargo did not provide OUT_DIR"));
    let permissions_path = write_app_permissions(&out_dir);
    let permissions_pattern = permissions_path
        .to_str()
        .expect("application-command permission path is not valid UTF-8")
        .to_owned();
    let permissions_pattern: &'static str = Box::leak(permissions_pattern.into_boxed_str());

    let app_manifest =
        tauri_build::AppManifest::new().permissions_path_pattern(permissions_pattern);
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(app_manifest))
        .unwrap_or_else(|error| panic!("Tauri build configuration failed: {error:#}"));
}
